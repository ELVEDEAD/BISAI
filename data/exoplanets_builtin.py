BLUE = (0.40, 0.65, 0.85)      # 岩石/类地
TEAL = (0.45, 0.78, 0.72)      # 超级地球/亚海王星
ORANGE = (0.88, 0.62, 0.35)    # 气态巨行星
PURPLE = (0.62, 0.55, 0.85)    # 特殊类型


def _color_by_mass(mass_earth, radius_earth=None):
    if mass_earth is None:
        return TEAL
    if mass_earth < 4:
        return BLUE
    if mass_earth < 30:
        return TEAL
    return ORANGE


def _b(name, host, period, a, ecc, incl, mass_earth, radius_earth,
       year, method, dist_pc, ra, dec, color=None):
    d = dict(name=name, host=host, period=period, a=a, ecc=ecc, incl=incl,
             mass_earth=mass_earth, radius_earth=radius_earth, year=year,
             method=method, dist_pc=dist_pc, ra=ra, dec=dec)
    d["color"] = color if color else _color_by_mass(mass_earth)
    return d


